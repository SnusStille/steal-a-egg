#!/usr/bin/env python3
"""Build a binary Roblox Studio-ready place (.rbxl) with the REAL world embedded.

Merges assets/world/EggHeistWorld.rbxm (generated by tools/build_world.py)
with every .luau file under src/ (Rojo naming conventions) into ONE open-and-Play
place file: Egg-Heist.rbxl (repo root).

Merge strategy (no CFrame decoding required):
  - World INST/PROP bytes are copied VERBATIM (world referents 0..513 untouched).
  - New referents (514+) are assigned to services/folders/scripts only.
  - PRNT is re-encoded as: world pairs (EggHeist root re-parented under the new
    Workspace) + new pairs, then roundtrip-verified on every build.
  - Only fully-understood property encodings are emitted: String (0x01),
    Bool (0x02). Scripts use inline Source (never SharedString).
  - Header class/instance counts are patched; META/SSTR copied verbatim.

Usage: python3 tools/build_binary_place.py
"""
import struct
import sys
from pathlib import Path

import lz4.block

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
WORLD = ROOT / "assets" / "world" / "EggHeistWorld.rbxm"

sys.path.insert(0, str(ROOT / "tools"))
from inspect_rbxm import read_chunks, uninterleave, zigzag  # noqa: E402


# ----------------------------------------------------------------------------
# binary encoders (inverses of the validated decoders in inspect_rbxm.py)
# ----------------------------------------------------------------------------

def interleave(values):
    """u32 list -> byte-interleaved bytes (most-significant group first)."""
    n = len(values)
    groups = [bytearray(n) for _ in range(4)]
    for i, v in enumerate(values):
        v &= 0xFFFFFFFF
        groups[0][i] = (v >> 24) & 0xFF
        groups[1][i] = (v >> 16) & 0xFF
        groups[2][i] = (v >> 8) & 0xFF
        groups[3][i] = v & 0xFF
    return b"".join(bytes(g) for g in groups)


def _zz_encode(n):
    return ((n << 1) ^ (n >> 31)) & 0xFFFFFFFF if n >= 0 else ((-n * 2 - 1) & 0xFFFFFFFF)


def encode_deltas(ids):
    """Referent list -> interleaved cumulative-zigzag-delta bytes."""
    out = []
    prev = 0
    for ref in ids:
        out.append(_zz_encode(ref - prev) & 0xFFFFFFFF)
        prev = ref
    return interleave(out)


def encode_strings(values):
    """List of str/bytes -> inline string array (u32LE len + bytes each)."""
    out = bytearray()
    for v in values:
        b = v.encode("utf-8") if isinstance(v, str) else bytes(v)
        out += struct.pack("<I", len(b))
        out += b
    return bytes(out)


def frame_chunk(name, payload, compress=True):
    if compress:
        raw = lz4.block.compress(payload, store_size=False)
        # lz4.block.compress must roundtrip through the reader's decompress call
        assert lz4.block.decompress(raw, uncompressed_size=len(payload)) == payload
        clen, ulen = len(raw), len(payload)
    else:
        raw = payload
        clen, ulen = 0, len(payload)
    return name.encode("ascii") + struct.pack("<III", clen, ulen, 0) + raw


# ----------------------------------------------------------------------------
# src/ tree -> content plan (Rojo naming conventions; must agree with
# default.project.json so `rojo build` produces the same game)
# ----------------------------------------------------------------------------

class Node:
    def __init__(self, class_name, name, props=None):
        self.class_name = class_name
        self.name = name
        self.props = props or {}  # prop name -> ("s", str) | ("b", bool)
        self.children = []
        self.ref = None


def node_for_file(path):
    name = path.name
    source = path.read_text(encoding="utf-8")
    if name.endswith(".server.luau"):
        n = Node("Script", name[: -len(".server.luau")])
        n.props = {"Disabled": ("b", False), "Source": ("s", source)}
        return n
    if name.endswith(".client.luau"):
        n = Node("LocalScript", name[: -len(".client.luau")])
        n.props = {"Disabled": ("b", False), "Source": ("s", source)}
        return n
    if name.endswith(".luau"):
        n = Node("ModuleScript", name[: -len(".luau")])
        n.props = {"Source": ("s", source)}
        return n
    return None


def node_for_dir(path):
    folder_name = path.name
    children = []
    init_source = None
    init_class = None
    for child in sorted(path.iterdir(), key=lambda p: p.name):
        if child.is_file() and child.suffix == ".luau":
            if child.name in ("init.luau", "init.server.luau", "init.client.luau"):
                init_source = child.read_text(encoding="utf-8")
                if child.name == "init.server.luau":
                    init_class = "Script"
                elif child.name == "init.client.luau":
                    init_class = "LocalScript"
                else:
                    init_class = "ModuleScript"
            else:
                item = node_for_file(child)
                if item:
                    children.append(item)
        elif child.is_dir():
            children.append(node_for_dir(child))
    if init_class and init_source is not None:
        n = Node(init_class, folder_name)
        n.props = {"Source": ("s", init_source)}
        if init_class != "ModuleScript":
            n.props["Disabled"] = ("b", False)
        n.children = children
        return n
    n = Node("Folder", folder_name)
    n.children = children
    return n


def service_children(name):
    path = SRC / name
    if not path.is_dir():
        return []
    kids = []
    for child in sorted(path.iterdir(), key=lambda p: p.name):
        if child.is_dir():
            kids.append(node_for_dir(child))
        elif child.is_file() and child.suffix == ".luau":
            item = node_for_file(child)
            if item:
                kids.append(item)
    return kids


SERVICE_CLASSES = {
    "Workspace", "Lighting", "ReplicatedStorage", "ServerScriptService",
    "StarterPlayer", "StarterGui", "ServerStorage", "SoundService", "Teams",
}


def build_content():
    """Services list; matches default.project.json services exactly."""
    services = []
    workspace = Node("Workspace", "Workspace")
    # No spawn stub: the world (EggHeist/Map/Spawn/SpawnLocation, built by
    # tools/build_world.py) carries a complete Neutral spawn that
    # WorldService.EnsureSpawn reuses and snaps onto the plaza at boot.
    workspace.children = []
    workspace.children.extend(service_children("Workspace"))
    services.append(workspace)
    services.append(Node("Lighting", "Lighting"))
    rs = Node("ReplicatedStorage", "ReplicatedStorage")
    rs.children = service_children("ReplicatedStorage")
    services.append(rs)
    sss = Node("ServerScriptService", "ServerScriptService")
    sss.children = service_children("ServerScriptService")
    services.append(sss)
    sp = Node("StarterPlayer", "StarterPlayer")
    sps = Node("StarterPlayerScripts", "StarterPlayerScripts")
    spd = SRC / "StarterPlayer" / "StarterPlayerScripts"
    if spd.is_dir():
        for child in sorted(spd.iterdir(), key=lambda p: p.name):
            if child.is_dir():
                sps.children.append(node_for_dir(child))
            elif child.is_file() and child.suffix == ".luau":
                item = node_for_file(child)
                if item:
                    sps.children.append(item)
    scs = Node("StarterCharacterScripts", "StarterCharacterScripts")
    scd = SRC / "StarterPlayer" / "StarterCharacterScripts"
    if scd.is_dir():
        for child in sorted(scd.iterdir(), key=lambda p: p.name):
            if child.is_dir():
                scs.children.append(node_for_dir(child))
            elif child.is_file() and child.suffix == ".luau":
                item = node_for_file(child)
                if item:
                    scs.children.append(item)
    sp.children = [sps]
    if scs.children or scd.is_dir():
        sp.children.append(scs)
    services.append(sp)
    sg = Node("StarterGui", "StarterGui")
    sg.children = service_children("StarterGui")
    services.append(sg)
    ss = Node("ServerStorage", "ServerStorage")
    ss.children = service_children("ServerStorage")
    services.append(ss)
    services.append(Node("SoundService", "SoundService"))
    services.append(Node("Teams", "Teams"))
    return services


